void* mtx_memcpy(void *dst, const void *src, size_t length) 
{
	if (dst == NULL || src == NULL || length <= 0) 
	{
        return NULL;
    }
    
    return mempcpy(dst, src, length);
}

int32_t mtx_atoi(const char *str);

int32_t mtx_atoi(const char *str)
{
	char *endptr;
	long val;
	
	//reset errno
	errno = 0;
	val = strtol(str, &endptr, 10);
	
	// error conditions
	if (endptr == str || *endptr != '\0')
	{
		fprintf(stderr, "Error: Invalid input string %s\n", str);
		return (-1);
	}
	
	if ((errno == ERANGE && (val == LONG_MAX || val == LONG_MIN)) || val > INT_MAX || val < INT_MIN)
	{
		fprintf(stderr, "Error: Value out of range\n");
		return (-1);
	}
	
	//success
	return (int32_t)val;
}

