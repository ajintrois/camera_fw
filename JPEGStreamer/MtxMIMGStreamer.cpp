/**
 * Maps a sockaddr_in (IPv4) to a sockaddr_storage (Generic)
 * @param src: Pointer to the existing IPv4 address structure
 * @param dst: Pointer to the storage structure to be populated
 */
void fill_sockaddr_storage(struct sockaddr_in const* src, struct sockaddr_storage* dst) {
    if (src == nullptr || dst == nullptr) return;

    // 1. Clear the destination to prevent garbage data
    memset(dst, 0, sizeof(struct sockaddr_storage));

    // 2. Copy the IPv4 structure into the storage
    // sockaddr_storage is guaranteed to be large enough to hold sockaddr_in
    mtx_memcpy(dst, src, sizeof(struct sockaddr_in));

    // 3. Explicitly set the family (though usually covers this)
    dst->ss_family = AF_INET;
}

/**
 * Converts a raw in_addr to the modern sockaddr_storage format
 * @param src_old: The legacy IPv4 address struct
 * @param port: The Port object (Live555 type)
 * @param dst: The destination storage struct
 */
void convert_to_storage(struct in_addr const& src_old, Port port, struct sockaddr_storage& dst) {
    // 1. Wipe the destination to ensure no "ghost" data exists
    memset(&dst, 0, sizeof(struct sockaddr_storage));

    // 2. Treat the storage as an IPv4 structure for easy assignment
    struct sockaddr_in* ipv4 = (struct sockaddr_in*)&dst;

    // 3. Populate the necessary fields
    ipv4->sin_family = AF_INET;
    ipv4->sin_addr = src_old;
    ipv4->sin_port = htons(port.num()); // Live555 Port.num() is usually in host order
}
